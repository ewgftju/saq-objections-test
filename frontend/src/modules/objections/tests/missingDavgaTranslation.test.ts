import assert from "node:assert/strict";
import test from "node:test";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { initialState } from "../../../api/objectionsRepository";
import { addDocument, applyAction } from "../services/workflow";
import { decisionProjectDavga, motivatedResponseDavga } from "../services/protocolReason";
import { actionForm } from "../formDefinitions";
import { DocumentContent } from "../components/DocumentModal";
import ActionModal from "../components/ActionModal";

for (const stage of ["decision-project", "motivated-response"] as const) for (const hasProject of stage === "motivated-response" ? [false, true] : [false]) {
  test(`${stage}, проект ${hasProject}: перевод принимается до формирования`, () => {
    let state = initialState();
    const c = state.cases[0];
    c.status = stage === "decision-project" ? "decision_project" : "decided";
    c.appealType = "Жалоба на уведомление";
    c.appealLanguage = "kk";
    const point = { ...c.issues.find(item => item.disputed)!, id: "p1", number: "1" };
    const second = { ...point, id: "p2", number: "2" };
    c.issues = [point, second];
    c.documents = [];
    c.certificate = { languages: ["ru"], davgaArguments: "", davgaArgumentsByPoint: { p1: "Справка 1", p2: "Справка 2" }, memberPositions: [] };
    c.votes = Object.fromEntries([point, second].map(item => [item.id, { yes: 1, no: 0, approved: true, chair: "chair", present: 1, eligible: 1, votes: { chair: "accept" } }]));
    c.meeting = { date: state.date, number: "ПЗ-1", audio: "", signed: state.date, languages: ["ru"], protocolVersions: [{ createdAt: state.date, signedAt: state.date, languages: ["ru"], author: "Исполнитель", rows: [point, second].map((item, i) => ({ pointId: item.id, pointNumber: item.number, memberId: "chair", memberName: "Председатель", vote: "accept", original: `Доводы рабочего органа (ДАВГА МФ РК): Исходные ${i+1}`, edited: `Доводы рабочего органа (ДАВГА МФ РК): Протокол ${i+1}` })) }] };
    addDocument(c, "work", state.date, "Справка по результатам изучения и анализа возражения", "certificate", "");
    c.documents.at(-1)!.certificateNumber = 4;
    addDocument(c, "commission", state.date, "Подписанный протокол заседания", "protocol", "");
    if (hasProject) addDocument(c, "director", state.date, "Подписанный проект решения", "decision-project", "");
    const action = stage === "decision-project" ? "create-decision-project" : "deliver";
    const fields = actionForm("propose-certificate-change", c, state.date, {}).fields;
    assert.ok(fields.some(field => field.name === "sourceDavga_p1" && field.value === "Протокол 1"));
    assert.ok(fields.some(field => field.name === "proposedDavgaKk_p1"));
    assert.throws(() => applyAction(state, c.id, action, "work", new FormData()), /Предложите перевод/);
    let html = renderToStaticMarkup(createElement(ActionModal, { c, action, date: state.date, role: "work", onSubmit() {}, onClose() {} }));
    assert.match(html, /Нет согласованных доводов ДАВГА на языке обращения/);
    const propose = new FormData(); propose.set("proposedDavgaKk_p1", "Қазақша 1"); propose.set("proposedDavgaKk_p2", "Қазақша 2");
    state = applyAction(state, c.id, "propose-certificate-change", "work", propose);
    let saved = state.cases.find(item => item.id === c.id)!;
    const pending = saved.certificateChangeRequests!.at(-1)!;
    assert.equal(pending.changes.length, 2);
    const withdraw = new FormData(); withdraw.set("withdrawCertificateProposal", pending.proposedAt);
    assert.throws(() => applyAction(state, c.id, action, "work", withdraw), /Предложите перевод/);
    html = renderToStaticMarkup(createElement(ActionModal, { c: saved, action, date: state.date, role: "work", onSubmit() {}, onClose() {} }));
    assert.match(html, /ожидает решения директора/);
    assert.doesNotMatch(html, /предложение будет отозвано/);
    const review = new FormData(); review.set("decision_p1_kk", "accepted"); review.set("decision_p2_kk", "rejected");
    state = applyAction(state, c.id, "review-certificate-change", "director", review);
    saved = state.cases.find(item => item.id === c.id)!;
    assert.equal(saved.certificate?.davgaArgumentsByPointKk?.p1, "Қазақша 1");
    assert.deepEqual(saved.certificate?.languages, ["kk"]);
    assert.equal(saved.documents.filter(item => item.kind === "certificate").at(-1)?.certificateNumber, 4);
    assert.throws(() => applyAction(state, c.id, action, "work", new FormData()), /пунктам: 2/);
    const retry = new FormData(); retry.set("proposedDavgaKk_p2", "Қазақша 2 түзетілген");
    state = applyAction(state, c.id, "propose-certificate-change", "work", retry);
    const accept = new FormData(); accept.set("decision_p2_kk", "accepted");
    state = applyAction(state, c.id, "review-certificate-change", "director", accept);
    saved = state.cases.find(item => item.id === c.id)!;
    const getDavga = stage === "decision-project" ? decisionProjectDavga : motivatedResponseDavga;
    assert.equal(getDavga(saved, "p1", "kk"), "Қазақша 1");
    assert.equal(getDavga(saved, "p2", "kk"), "Қазақша 2 түзетілген");
    assert.equal(saved.meeting?.protocolVersions?.at(-1)?.rows[0].editedKk, undefined);
    state = applyAction(state, c.id, action, "work", new FormData());
    saved = state.cases.find(item => item.id === c.id)!;
    const doc = saved.documents.filter(item => item.kind === (stage === "decision-project" ? "decision-project" : "final-response")).at(-1)!;
    html = renderToStaticMarkup(createElement(DocumentContent, { c: saved, kind: doc.kind, document: doc, language: "kk" }));
    assert.match(html, /Қазақша 1/);
    assert.match(html, /Қазақша 2 түзетілген/);
  });
}

test("русское обращение: казахский протокол не выдаётся за русский текст", () => {
  const state = initialState();
  const c = state.cases[0];
  c.appealLanguage = "ru";
  c.status = "decision_project";
  c.appealType = "Жалоба на уведомление";
  const point = c.issues.find(item => item.disputed)!;
  c.issues = [point];
  c.documents = [];
  c.certificate = { languages: ["kk"], davgaArguments: "", davgaArgumentsByPointKk: { [point.id]: "Қазақша" }, memberPositions: [] };
  c.votes = { [point.id]: { yes: 1, no: 0, approved: true, chair: "chair", present: 1, eligible: 1, votes: { chair: "accept" } } };
  c.meeting = { date: state.date, number: "ПЗ-1", audio: "", signed: state.date, languages: ["kk"], protocolVersions: [{ createdAt: state.date, signedAt: state.date, languages: ["kk"], author: "Исполнитель", rows: [{ pointId: point.id, pointNumber: point.number, memberId: "chair", memberName: "Председатель", vote: "accept", original: "Доводы рабочего органа (ДАВГА МФ РК): Старый RU", edited: "Доводы рабочего органа (ДАВГА МФ РК): Старый RU", editedKk: "Жұмыс органының (ҚР ҚМ ДАВГА) дәлелдері: Қазақша" }] }] };
  assert.equal(decisionProjectDavga(c, point.id, "ru"), "");
  assert.equal(decisionProjectDavga(c, point.id, "kk"), "Қазақша");
  assert.throws(() => applyAction(state, c.id, "create-decision-project", "work", new FormData()), /Предложите перевод/);
});

test("русские доводы справки предлагаются для сверки, а в проект попадают после принятия", () => {
  let state = initialState();
  const c = state.cases[0];
  c.appealLanguage = "ru"; c.appealType = "Жалоба на уведомление"; c.status = "decision_project"; c.orgTranslations = { kk: "Ұйым" };
  const point = { ...c.issues.find(item => item.disputed)!, id: "p1", number: "1" }; c.issues = [point]; c.documents = [];
  c.certificate = { languages: ["ru", "kk"], davgaArguments: "", davgaArgumentsByPoint: { p1: "Русская основа из справки" }, davgaArgumentsByPointKk: { p1: "Бастапқы дәлел" }, memberPositions: [] };
  addDocument(c, "work", state.date, "Подписанная справка", "certificate", "");
  c.certificate.languages = ["kk"];
  c.votes = { p1: { yes: 1, no: 0, approved: true, chair: "chair", present: 1, eligible: 1, votes: { chair: "accept" } } };
  c.meeting = { date: state.date, number: "ПЗ-1", audio: "", signed: state.date, languages: ["kk"], protocolVersions: [{ createdAt: state.date, signedAt: state.date, languages: ["kk"], author: "Исполнитель", rows: [{ pointId: "p1", pointNumber: "1", memberId: "chair", memberName: "Председатель", vote: "accept", original: "", edited: "", editedKk: "Жұмыс органының (ҚР ҚМ ДАВГА) дәлелдері: Өзгертілген дәлел" }] }] };
  const fields = actionForm("propose-certificate-change", c, state.date, {}).fields;
  assert.equal(fields.find(field => field.name === "sourceDavga_p1")?.value, "Өзгертілген дәлел");
  const draft = fields.find(field => field.name === "proposedDavga_p1")!;
  assert.equal(draft.value, "Русская основа из справки");
  assert.match(draft.label, /из справки, проверьте соответствие протоколу/);
  assert.equal(decisionProjectDavga(c, "p1", "ru"), "");
  assert.throws(() => applyAction(state, c.id, "create-decision-project", "work", new FormData()), /Предложите перевод/);
  const proposal = new FormData(); proposal.set("proposedDavga_p1", draft.value!);
  state = applyAction(state, c.id, "propose-certificate-change", "work", proposal);
  let saved = state.cases.find(item => item.id === c.id)!;
  assert.equal(saved.certificateChangeRequests?.at(-1)?.changes[0].before, "");
  assert.equal(decisionProjectDavga(saved, "p1", "ru"), "");
  const review = new FormData(); review.set("decision_p1", "accepted");
  state = applyAction(state, c.id, "review-certificate-change", "director", review);
  saved = state.cases.find(item => item.id === c.id)!;
  assert.equal(decisionProjectDavga(saved, "p1", "ru"), "Русская основа из справки");
  state = applyAction(state, c.id, "create-decision-project", "work", new FormData());
  const result = state.cases.find(item => item.id === c.id)!;
  assert.match(renderToStaticMarkup(createElement(DocumentContent, { c: result, kind: "decision-project", document: result.documents.at(-1), language: "ru" })), /Русская основа из справки/);
});
