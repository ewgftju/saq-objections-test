import assert from "node:assert/strict";
import test from "node:test";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { initialState } from "../../../api/objectionsRepository";
import { actionForm } from "../formDefinitions";
import { addDocument, additionalActions, applyAction, nextAction } from "../services/workflow";
import { certificateBasisForPoint, currentProtocolRows, protocolDavgaFromReason } from "../services/protocolReason";
import ActionModal from "../components/ActionModal";

test("директор принимает и отклоняет изменения справки по пунктам, сохраняя старую версию", () => {
  let state = initialState();
  const c = state.cases[0];
  c.status = "meeting";
  const first = c.issues.find((point) => point.disputed)!;
  const second = { ...first, id: "second-test-point", number: "2", disputed: true };
  c.issues = [first, second];
  c.documents = c.documents.filter((document) => document.kind !== "certificate");
  c.certificate = { davgaArguments: "", davgaArgumentsByPoint: { [first.id]: "Исходные доводы 1", [second.id]: "Исходные доводы 2" }, memberPositions: [] };
  c.members = [{ id: "chair", name: "Председатель", present: true, recused: false, reason: "" }];
  addDocument(c, "work", state.date, "Исходная справка", "certificate", "");
  c.meeting = { date: state.date, number: "", audio: "", protocolVersions: [{ author: "Исполнитель", createdAt: "2026-10-28T10:00:00Z", rows: [{ pointId: first.id, pointNumber: first.number, memberId: "chair", memberName: "Председатель", vote: "accept", original: "old", edited: "old edit" }] }] };
  assert.ok(additionalActions(c).some((item) => item.action === "propose-certificate-change"));
  assert.ok(!additionalActions(c).some((item) => item.action === "edit-certificate"));
  const form = new FormData();
  form.set(`proposedDavga_${first.id}`, "Новые доводы 1");
  form.set(`proposedDavga_${second.id}`, "Новые доводы 2");
  form.set("changeReason", "Уточнение");
  state = applyAction(state, c.id, "propose-certificate-change", "work", form);
  let saved = state.cases.find((item) => item.id === c.id)!;
  assert.equal(saved.certificate?.davgaArgumentsByPoint?.[first.id], "Исходные доводы 1");
  assert.equal(nextAction(saved)?.action, "review-certificate-change");
  assert.throws(() => applyAction(state, c.id, "vote", "work", new FormData()), /Сначала директор/);
  assert.throws(() => applyAction(state, c.id, "review-certificate-change", "work", new FormData()));
  const fields = actionForm("review-certificate-change", saved, state.date, {}).fields;
  assert.equal(fields.find((field) => field.name === `before_${first.id}`)?.value, "Исходные доводы 1");
  const reviewHtml = renderToStaticMarkup(createElement(ActionModal, { c: saved, action: "review-certificate-change", date: state.date, role: "director", onSubmit() {}, onClose() {} }));
  assert.match(reviewHtml, /readonly=""/i);
  assert.match(reviewHtml, /Новые доводы 1/);
  const review = new FormData();
  review.set(`decision_${first.id}`, "accepted");
  review.set(`decision_${second.id}`, "rejected");
  review.set("reviewComment", "Проверено");
  state = applyAction(state, c.id, "review-certificate-change", "director", review);
  saved = state.cases.find((item) => item.id === c.id)!;
  assert.equal(saved.certificate?.davgaArgumentsByPoint?.[first.id], "Новые доводы 1");
  assert.equal(saved.certificate?.davgaArgumentsByPoint?.[second.id], "Исходные доводы 2");
  assert.equal(protocolDavgaFromReason(certificateBasisForPoint(saved, first)), "Новые доводы 1");
  assert.equal(saved.documents.filter((document) => document.kind === "certificate").length, 2);
  assert.equal(saved.documents.find((document) => document.name === "Исходная справка")?.snapshot?.certificate?.davgaArgumentsByPoint?.[first.id], "Исходные доводы 1");
  assert.equal(saved.certificateChangeRequests?.at(-1)?.changes[1].decision, "rejected");
  assert.equal(saved.certificateChangeRequests?.at(-1)?.reviewComment, "Проверено");
  assert.equal(currentProtocolRows(saved), undefined);
  assert.equal(nextAction(saved)?.action, "vote");
  const protocolForm = new FormData();
  protocolForm.set("protocolDate", state.date);
  for (const point of [first, second]) {
    protocolForm.set(`protocolVote_${point.id}_chair`, "accept");
    protocolForm.set(`protocolDavga_${point.id}_chair`, protocolDavgaFromReason(certificateBasisForPoint(saved, point)));
  }
  state = applyAction(state, c.id, "vote", "work", protocolForm);
  saved = state.cases.find((item) => item.id === c.id)!;
  assert.equal(saved.meeting?.protocolVersions?.length, 2);
  assert.match(saved.meeting!.protocolVersions![1].rows[0].original, /Новые доводы 1/);
  assert.equal(saved.meeting!.protocolVersions![1].rows[0].original, saved.meeting!.protocolVersions![1].rows[0].edited);
});

test("при отказе по всем пунктам справка и её версия не меняются", () => {
  let state = initialState();
  const c = state.cases[0]; c.status = "meeting";
  const points = c.issues.filter((point) => point.disputed);
  c.documents = c.documents.filter((document) => document.kind !== "certificate");
  c.certificate = { davgaArguments: "Прежний текст", memberPositions: [] };
  const form = new FormData();
  for (const point of points) form.set(`proposedDavga_${point.id}`, "Предложенный текст");
  state = applyAction(state, c.id, "propose-certificate-change", "work", form);
  const review = new FormData();
  for (const point of points) review.set(`decision_${point.id}`, "rejected");
  state = applyAction(state, c.id, "review-certificate-change", "director", review);
  const saved = state.cases.find((item) => item.id === c.id)!;
  assert.equal(saved.certificate?.davgaArguments, "Прежний текст");
  assert.equal(saved.certificateRevision, undefined);
  assert.equal(saved.documents.filter((document) => document.kind === "certificate").length, 0);
});
